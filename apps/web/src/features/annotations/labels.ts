export function annotationLabels(locale: "zh" | "en") {
  return locale === "zh" ? zh : en;
}
export function annotationErrorLabel(
  locale: "zh" | "en",
  code: string,
): string {
  const t = annotationLabels(locale);
  return code === "REVISION_CONFLICT"
    ? t.conflict
    : code === "SNAPSHOT_CHANGED"
      ? t.snapshotConflict
      : code === "REQUEST_OUTCOME_UNKNOWN"
        ? t.outcomeUnknown
        : code === "INVALID_ANNOTATION_REPLY"
          ? t.invalidReply
          : t.invalid;
}
