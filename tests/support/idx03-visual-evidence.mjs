import assert from "node:assert/strict";
import {readFile,writeFile,mkdtemp,rm} from "node:fs/promises";
import {join,resolve} from "node:path";
import {tmpdir} from "node:os";
import {chromium,expect} from "@playwright/test";
import {startProduction,http,denyExternalRequests} from "./production.mjs";
const out=resolve("docs/superpowers/reviews/idx03-2026-10-10");
const previous=JSON.parse(await readFile(join(out,"references-product.json"),"utf8"));
assert.equal(previous.status,"passed");
const runtime=await mkdtemp(join(tmpdir(),"atlasmode-idx03-visual-"));
let server,browser;
const errors=[],external=[];
try{
 server=await startProduction(join(runtime,"data"));
 browser=await chromium.launch();
 const context=await browser.newContext({viewport:{width:1600,height:1000}});
 await denyExternalRequests(context,external);
 const page=await context.newPage();
 page.on("pageerror",error=>errors.push(String(error)));page.on("console",message=>{if(message.type()==="error")errors.push(message.text());});
 await page.goto(server.url);
 if(await page.locator(".welcome").count())await page.locator(".welcome").getByRole("button",{name:"选择本地项目",exact:true}).click();
 await page.getByRole("textbox",{name:"本地项目路径"}).fill(previous.target);
 const opened=page.waitForResponse(response=>response.url().endsWith("/api/projects")&&response.request().method()==="POST");
 await page.getByRole("button",{name:"打开并索引",exact:true}).click();
 const project=await (await opened).json(),base="/api/projects/"+project.id;
 const snapshot=await http(server.url,base+"/snapshot");
 assert.equal(snapshot.contentHash,previous.afterReferences.contentHash);
 await page.getByRole("combobox",{name:"界面语言"}).selectOption("en");
 await page.getByRole("button",{name:"Advanced controls",exact:true}).click();
 await page.locator(".advanced-navigation-content > details > summary").click();
 const panel=page.getByTestId("configuration-project-graph");
 await panel.locator(":scope > summary").click();
 await expect(panel).toContainText("Partial captured graph");
 await expect(panel).toContainText("Source scopes: 66");
 await panel.getByText("Observed projects (6/6)",{exact:true}).click();
 const align=()=>panel.evaluate(element=>{
   const nav=element.closest(".navigation");
   nav.scrollTop+=element.getBoundingClientRect().top-nav.getBoundingClientRect().top-16;
 });
 await align();
 await page.screenshot({path:join(out,"references-graph-overview.png"),fullPage:true});
 await page.getByRole("textbox",{name:"Search functions"}).fill("noImport");
 const searched=page.waitForResponse(response=>response.url().includes("/functions?"));
 await page.getByRole("button",{name:"Search",exact:true}).click();await searched;
 await page.locator(".navigation .compact-search .node-list button").filter({has:page.getByText("ƒ noImport",{exact:true})}).click();
 const sourceTab=page.locator(".inspector .tabs").getByRole("button",{name:"View source",exact:true});if(await sourceTab.count())await sourceTab.click();
 await expect(page.getByTestId("source-snippet")).toContainText("helper()");
 await expect(page.locator(".inspector")).toContainText("Unresolved");
 await align();
 await page.screenshot({path:join(out,"references-no-import-unknown.png"),fullPage:true});
 await page.getByRole("combobox",{name:"Interface language"}).selectOption("zh");
 await expect(panel.locator(":scope > summary")).toHaveText("配置项目图");
 await expect(panel).toContainText("源码归属: 66");
 await expect(panel).toContainText("configs/app.json");
 await align();
 await page.screenshot({path:join(out,"references-graph-zh.png"),fullPage:true});
 assert.deepEqual(errors,[]);assert.deepEqual(external,[]);
 await writeFile(join(out,"supplementary-visual.json"),JSON.stringify({status:"passed",stage:"same compiled graph final-state visual evidence",project,contentHash:snapshot.contentHash,sourceTarget:previous.target,coverage:snapshot.coverage,errors,external},null,2));
 console.log(JSON.stringify({status:"passed",contentHash:snapshot.contentHash,errors,external}));
}finally{await browser?.close();await server?.stop();await rm(runtime,{recursive:true,force:true});}
